def fill(sec, d, styles=(), charts=None):
    for a, b in styles:
        assert a in sec, a
        sec = sec.replace(a, b, 1)
    if charts:
        it = iter(charts)
        sec = re.sub(r"data-chart='[^']*'", lambda m: "data-chart='" + json.dumps(next(it), ensure_ascii=False) + "'", sec)
    d = {"출처": SRC, **d}
    for k, v in d.items():
        sec = sec.replace("{{" + k + "}}", v)
    return sec


